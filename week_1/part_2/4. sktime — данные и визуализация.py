# |---|---|
# | `sktime.forecasting` | прогнозирование: `NaiveForecaster`, `ARIMA`, `AutoETS`, `Prophet`, … |
# | `sktime.classification` | классификация рядов |
# | `sktime.regression`, `sktime.clustering` | регрессия и кластеризация рядов |
