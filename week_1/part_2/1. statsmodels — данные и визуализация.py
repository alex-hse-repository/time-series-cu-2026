# 🔍 Сравните три коррелограммы справа — это три разных «портрета» ряда:
#
# | Ряд | ACF | Вывод |
# |---|---|---|
# | AirPassengers | затухает медленно, пики на 12/24/36 | тренд + годовая сезонность |
